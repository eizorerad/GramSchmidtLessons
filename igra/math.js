"use strict";

const M = {

  // скалярное произведение: перемножили по позициям и сложили (урок 03)
  dot(a, b) {
    let s = 0;
    for (let i = 0; i < a.length; i++) s += a[i] * b[i];
    return s;
  },

  // длина вектора - корень из скалярного произведения с самим собой (урок 03)
  norm(v) {
    return Math.sqrt(M.dot(v, v));
  },

  // сложение и вычитание по позициям (урок 02)
  add(a, b) { return a.map((x, i) => x + b[i]); },
  sub(a, b) { return a.map((x, i) => x - b[i]); },

  // умножение вектора на число (урок 02)
  scale(k, v) { return v.map(x => k * x); },

  // нормализация: делим каждую координату на длину (урок 03)
  normalize(v) {
    const n = M.norm(v);
    return n < 1e-12 ? v.slice() : M.scale(1 / n, v);
  },

  // тень (проекция) вектора v на ЕДИНИЧНЫЙ вектор e: (v·e)e (урок 04)
  project(v, e) {
    return M.scale(M.dot(v, e), e);
  },

  // вычесть тень: остаётся часть, перпендикулярная e (урок 04)
  subtractShadow(v, e) {
    return M.sub(v, M.project(v, e));
  },

  // процесс Грама-Шмидта, как в уроке 09 (нули для зависимых векторов)
  gramSchmidt(vectors) {
    const eps = 1e-10;
    const B = vectors.map(v => v.slice());
    for (let j = 0; j < B.length; j++) {
      for (let i = 0; i < j; i++) {
        B[j] = M.sub(B[j], M.project(B[j], B[i]));   // минус тень на e_i
      }
      B[j] = M.norm(B[j]) > eps ? M.normalize(B[j]) : B[j].map(() => 0);
    }
    return B;
  },

  // ---- матрицы 2x2 (для зеркала, урок 10) ----

  // матрица по столбцам-осям: E = [e1 e2]
  matFromCols(e1, e2) { return [[e1[0], e2[0]], [e1[1], e2[1]]]; },

  // транспонирование: строки и столбцы меняются местами
  matT(A) { return [[A[0][0], A[1][0]], [A[0][1], A[1][1]]]; },

  // матрица действует на вектор
  matVec(A, v) {
    return [A[0][0] * v[0] + A[0][1] * v[1],
            A[1][0] * v[0] + A[1][1] * v[1]];
  },

  // умножение матриц
  matMul(A, B) {
    return [[A[0][0]*B[0][0] + A[0][1]*B[1][0], A[0][0]*B[0][1] + A[0][1]*B[1][1]],
            [A[1][0]*B[0][0] + A[1][1]*B[1][0], A[1][0]*B[0][1] + A[1][1]*B[1][1]]];
  },

  // обратная матрица 2x2 (нужна, чтобы переводить клики мыши в координаты
  // искажённого мира; для ортонормированной матрицы это просто транспонирование)
  matInv(A) {
    const d = A[0][0] * A[1][1] - A[0][1] * A[1][0];
    return [[ A[1][1] / d, -A[0][1] / d],
            [-A[1][0] / d,  A[0][0] / d]];
  },

  // матрица отражения в зеркале вдоль направления dir: T = E·TE·Eᵀ (урок 10)
  reflectionMatrix(dir) {
    const e1 = M.normalize(dir);
    const e2 = [-e1[1], e1[0]];            // перпендикуляр (поворот на 90°)
    const E = M.matFromCols(e1, e2);
    const TE = [[1, 0], [0, -1]];          // простое отражение "в мире зеркала"
    return M.matMul(M.matMul(E, TE), M.matT(E));
  },

  // почти ли равны два числа / вектора (компьютерный ноль, урок 03)
  близко(a, b, eps) { return Math.abs(a - b) < (eps || 1e-6); },
  близкиВекторы(a, b, eps) {
    return a.length === b.length && a.every((x, i) => Math.abs(x - b[i]) < (eps || 1e-6));
  },
};

