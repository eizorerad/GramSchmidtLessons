import numpy as np
import numpy.linalg as la

# ======================= МЕНЯЙ МЕНЯ =======================
v = np.array([3, 4], dtype=np.float64)   # первый вектор
w = np.array([1, 2], dtype=np.float64)   # второй вектор
# ==========================================================

print("=" * 50)
print("1. САМИ ВЕКТОРЫ")
print("v =", v)
print("w =", w)

print("=" * 50)
print("2. АРИФМЕТИКА (урок 02)")
print("v + w   =", v + w)      # сложение по позициям
print("v - w   =", v - w)      # вычитание по позициям
print("2 * v   =", 2 * v)      # растянуть в 2 раза
print("v / 2   =", v / 2)      # сжать в 2 раза

print("=" * 50)
print("3. ДЛИНА И НОРМАЛИЗАЦИЯ (урок 03)")
print("длина v      =", la.norm(v))       # теорема Пифагора внутри
e = v / la.norm(v)                        # нормализация: делим на длину
print("e = v/|v|    =", e)
print("длина e      =", la.norm(e))       # всегда 1.0

print("=" * 50)
print("4. СКАЛЯРНОЕ ПРОИЗВЕДЕНИЕ (урок 03)")
print("v @ w =", v @ w)   # число! ноль означал бы: перпендикулярны
print("v * w =", v * w)   # а это НЕ скалярное: поэлементное, вектор
if abs(v @ w) < 1e-10:
    print("   -> v и w ПЕРПЕНДИКУЛЯРНЫ")
else:
    print("   -> v и w не перпендикулярны")

print("=" * 50)
print("5. ПРОЕКЦИЯ-ТЕНЬ (урок 04): тень w на направление v")
dlina_teni = w @ e                 # число: длина тени w на единичный e
ten = dlina_teni * e               # сама тень (вектор вдоль e)
perpendikulyar = w - ten           # что осталось: часть w поперёк e
print("длина тени      =", dlina_teni)
print("тень            =", ten)
print("перпендикуляр   =", perpendikulyar)
print("проверка (0?)   =", perpendikulyar @ e)   # ~0 = перпендикулярно!

print("=" * 50)
